import type { LifeGraphEdge, EdgeType, EntityType, GraphData, EdgeFilter } from '@/types/lifeGraph'
import { validateEdge, detectCycle, extractSubgraph, convertToGraphData, getOppositeEdgeType, isDirectedEdge } from '@/engine'
import { graphRepository } from './graphRepository'

export const graphService = {
  async connect(
    userId: string,
    sourceEntityId: string,
    sourceEntityType: EntityType,
    targetEntityId: string,
    targetEntityType: EntityType,
    edgeType: EdgeType,
    weight?: number,
    metadata?: Record<string, unknown>,
  ): Promise<{ edge: LifeGraphEdge | null; error: string | null }> {
    const validationError = validateEdge(sourceEntityId, targetEntityId, sourceEntityType, targetEntityType)
    if (validationError) return { edge: null, error: validationError }

    const existing = await graphRepository.getEdgeBetween(sourceEntityId, targetEntityId, edgeType)
    if (existing) return { edge: existing, error: null }

    if (isDirectedEdge(edgeType)) {
      const existingEdges = await graphRepository.getAllEdges(userId)
      const cycleDetected = detectCycle(existingEdges, {
        sourceEntityId,
        targetEntityId,
        edgeType,
      })
      if (cycleDetected) return { edge: null, error: 'This edge would create a cycle' }
    }

    const edge = await graphRepository.createEdge({
      userId,
      sourceEntityId,
      sourceEntityType,
      targetEntityId,
      targetEntityType,
      edgeType,
      weight,
      metadata,
    })

    const oppositeType = getOppositeEdgeType(edgeType)
    if (oppositeType !== edgeType) {
      const existingOpposite = await graphRepository.getEdgeBetween(targetEntityId, sourceEntityId, oppositeType)
      if (!existingOpposite) {
        await graphRepository.createEdge({
          userId,
          sourceEntityId: targetEntityId,
          sourceEntityType: targetEntityType,
          targetEntityId: sourceEntityId,
          targetEntityType: sourceEntityType,
          edgeType: oppositeType,
          weight,
          metadata: { autoGenerated: true },
        })
      }
    }

    return { edge, error: null }
  },

  async disconnect(id: string): Promise<{ error: string | null }> {
    await graphRepository.deleteEdge(id)
    return { error: null }
  },

  async getGraphForEntity(entityId: string, entityType: EntityType): Promise<LifeGraphEdge[]> {
    return graphRepository.getEdgesForEntity(entityId, entityType)
  },

  async getGraphForGoal(goalId: string): Promise<GraphData> {
    const edges = await graphRepository.getEdgesForEntity(goalId, 'goal')
    const connectedIds = new Set<string>()
    connectedIds.add(goalId)
    edges.forEach((e) => {
      connectedIds.add(e.sourceEntityId)
      connectedIds.add(e.targetEntityId)
    })

    const nodes = new Map<string, { type: EntityType; label: string }>()
    nodes.set(goalId, { type: 'goal', label: '' })
    for (const edge of edges) {
      if (!nodes.has(edge.sourceEntityId)) {
        nodes.set(edge.sourceEntityId, {
          type: edge.sourceEntityType,
          label: edge.sourceEntityId,
        })
      }
      if (!nodes.has(edge.targetEntityId)) {
        nodes.set(edge.targetEntityId, {
          type: edge.targetEntityType,
          label: edge.targetEntityId,
        })
      }
    }
    return convertToGraphData(nodes, edges)
  },

  async getSubgraph(userId: string, entityId: string, entityType: EntityType, depth: number = 2): Promise<GraphData> {
    const allEdges = await graphRepository.getAllEdges(userId)
    const filteredEdges = allEdges.filter(
      (e) =>
        e.sourceEntityId === entityId || e.targetEntityId === entityId ||
        e.sourceEntityType === entityType || e.targetEntityType === entityType,
    )
    const subgraphEdges = extractSubgraph(filteredEdges, entityId, depth)

    const nodes = new Map<string, { type: EntityType; label: string }>()
    for (const edge of subgraphEdges) {
      if (!nodes.has(edge.sourceEntityId)) {
        nodes.set(edge.sourceEntityId, { type: edge.sourceEntityType, label: edge.sourceEntityId })
      }
      if (!nodes.has(edge.targetEntityId)) {
        nodes.set(edge.targetEntityId, { type: edge.targetEntityType, label: edge.targetEntityId })
      }
    }
    if (!nodes.has(entityId)) {
      nodes.set(entityId, { type: entityType, label: entityId })
    }

    return convertToGraphData(nodes, subgraphEdges)
  },

  async getEdges(userId: string, filter?: EdgeFilter): Promise<LifeGraphEdge[]> {
    return graphRepository.getEdges(userId, filter)
  },
}
